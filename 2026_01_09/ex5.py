#Exercício 5 Dada a tupla tupla = (3, 15, 7, 42, 8, 19, 4, 26, 11) , imprima, usando fatiamento: (a) os
#4 primeiros elementos; (b) os 3 últimos elementos; (c) a tupla invertida

tupla = (3, 15, 7, 42, 8, 19, 4, 26, 11)
print(f'(a) Os 4 primeiros elementos: {tupla[:4]}')
print(f'(b) Os 3 últimos elementos: {tupla[-3:]}')
print(f'(c) A tupla invertida: {tupla[::-1]}')
